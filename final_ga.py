#!/usr/bin/env python3
"""
final_ga.py
Optimizes the genome for 'robust_circuit.qpy' using a Genetic Algorithm.
STRICT MODE: No random genomes. Starts ONLY with k-NN suggestions.
Reuses functions from final_dg_v4_robust.py.
"""

import pandas as pd
import numpy as np
import json
import ast
import random
import warnings
from tqdm import tqdm

# Qiskit Imports
from qiskit import qpy
from qiskit_aer import AerSimulator

# --- IMPORTING FROM YOUR DATA GENERATION SCRIPT ---
# Ensure final_dg_v4_robust.py is in the same directory
try:
    from final_dg import (
        GENE_MAP, 
        get_noise_model, 
        compute_fidelity, 
        safe_transpile,
        N_QUBITS,
        GENOME_LENGTH
    )
except ImportError:
    raise ImportError("Error: 'final_dg_v4_robust.py' not found! Make sure it is in the same folder.")

# ---------------- CONFIGURATION ----------------
TARGET_QPY_FILE = 'target_circuit.qpy'  # The circuit generated by your DG script
INIT_POP_CSV = 'structural_suggestions.csv'  # Output from k-NN
OUTPUT_CSV = 'ga_best_result.csv'

# GA Parameters
POPULATION_SIZE = 20    # Small but focused population (since we only have 3 seeds)
GENERATIONS = 200
MUTATION_RATE = 0.8     # Slightly higher mutation to explore variations of the top 3
ELITISM_COUNT = 20       # Save the absolute best
GENE_KEYS = list(GENE_MAP.keys())

RNG = random.Random(42)

# ---------------- HELPER FUNCTIONS ----------------

def parse_genome_string(s):
    """Parses genome string from CSV."""
    try:
        if isinstance(s, list): return s
        # Fix potential quote issues in CSV strings
        return json.loads(s.replace("'", '"'))
    except:
        try: return ast.literal_eval(s)
        except: return []

def apply_genome(qc, genome_seq):
    """Applies genes using the imported GENE_MAP."""
    temp_qc = qc.copy()
    for gene_name in genome_seq:
        if gene_name in GENE_MAP:
            temp_qc = GENE_MAP[gene_name](temp_qc)
    return temp_qc

def crossover(parent1, parent2):
    """Single point crossover between two genomes."""
    if len(parent1) < 2: return parent1
    point = RNG.randint(1, len(parent1) - 1)
    child = parent1[:point] + parent2[point:]
    return child

def mutate(genome):
    """Mutates one gene in the sequence to a neighbor from GENE_MAP."""
    new_genome = genome.copy()
    idx = RNG.randint(0, len(genome) - 1)
    new_genome[idx] = RNG.choice(GENE_KEYS)
    return new_genome

# ---------------- MAIN SCRIPT ----------------

def main():
    print(f"--- Starting GA (Strict Mode) ---")
    
    # 1. Load Target Circuit
    try:
        with open(TARGET_QPY_FILE, 'rb') as fd:
            # qpy.load returns a list of circuits
            target_qc = qpy.load(fd)[0]
        print(f"Loaded target circuit: {TARGET_QPY_FILE}")
    except FileNotFoundError:
        print(f"Error: {TARGET_QPY_FILE} not found. Run final_dg_v4_robust.py first.")
        return

    # 2. Setup Simulation Environment (Using imported functions)
    noise_model = get_noise_model()
    sim = AerSimulator(method='density_matrix')

    # Calculate Baseline Fidelity (Before any GA)
    # Using safe_transpile with level 0 to ensure simulator compatibility
    baseline_qc = safe_transpile(target_qc, optimization_level=0)
    baseline_fid = compute_fidelity(baseline_qc, noise_model, sim)
    print(f"Baseline Fidelity (No Mitigation): {baseline_fid:.4f}")

    # 3. Initialize Population (STRICTLY FROM CSV)
    population = []
    try:
        df = pd.read_csv(INIT_POP_CSV)
        print(f"Loading seeds from {INIT_POP_CSV}...")
        
        # Load the k-NN suggestions
        seeds = []
        for g_str in df['suggested_genome']:
            g = parse_genome_string(g_str)
            if len(g) == GENOME_LENGTH:
                seeds.append(g)
        
        if not seeds:
            raise ValueError("No valid genomes found in CSV.")
            
        print(f"Found {len(seeds)} seed genomes from k-NN.")
        
        # Fill population ONLY using these seeds
        # First, add the original seeds
        population.extend(seeds)
        
        # Fill the rest by mutating the seeds (No random generation)
        while len(population) < POPULATION_SIZE:
            parent = RNG.choice(seeds)
            child = mutate(parent) # Create variation
            population.append(child)
            
    except Exception as e:
        print(f"Critical Error loading population: {e}")
        return

    print(f"Population initialized: {len(population)} individuals (All derived from k-NN).")

    # 4. Evolution Loop
    best_global_genome = None
    best_global_fid = -1.0
    
    # Progress bar
    pbar = tqdm(range(GENERATIONS), desc="Evolving")
    
    for gen in pbar:
        # A. Evaluate
        scores = []
        for genome in population:
            # Apply genes
            mitigated_qc = apply_genome(target_qc, genome)
            # Transpile lightly (level 0) to keep gene structure
            mitigated_qc_t = safe_transpile(mitigated_qc, optimization_level=0)
            # Compute fidelity
            fid = compute_fidelity(mitigated_qc_t, noise_model, sim)
            scores.append((genome, fid))

        # B. Rank
        scores.sort(key=lambda x: x[1], reverse=True)
        
        # Track Best
        gen_best_genome, gen_best_fid = scores[0]
        if gen_best_fid > best_global_fid:
            best_global_fid = gen_best_fid
            best_global_genome = gen_best_genome

        # Update Display
        pbar.set_postfix({'Best': f"{best_global_fid:.4f}", 'Gain': f"+{best_global_fid - baseline_fid:.4f}"})

        # C. Next Generation Generation
        # 1. Elitism: Keep the best one(s) as is
        new_population = [x[0] for x in scores[:ELITISM_COUNT]]
        
        # 2. Mating Pool: Select top performers to be parents
        parents_pool = [x[0] for x in scores[:len(scores)//2]] 
        
        # 3. Fill rest using Crossover & Mutation (Strictly internal breeding)
        while len(new_population) < POPULATION_SIZE:
            p1 = RNG.choice(parents_pool)
            p2 = RNG.choice(parents_pool)
            
            child = crossover(p1, p2)
            
            if RNG.random() < MUTATION_RATE:
                child = mutate(child)
                
            new_population.append(child)
            
        population = new_population

    # 5. Save Results
    print(f"\n--- Optimization Complete ---")
    print(f"Baseline Fidelity:     {baseline_fid:.4f}")
    print(f"Optimized Fidelity:    {best_global_fid:.4f}")
    print(f"Net Improvement:       {best_global_fid - baseline_fid:.4f}")
    print(f"Best Genome Sequence:  {best_global_genome}")

    result_data = {
        'circuit_file': [TARGET_QPY_FILE],
        'baseline_fidelity': [baseline_fid],
        'optimized_fidelity': [best_global_fid],
        'improvement': [best_global_fid - baseline_fid],
        'best_genome': [json.dumps(best_global_genome)]
    }
    
    res_df = pd.DataFrame(result_data)
    res_df.to_csv(OUTPUT_CSV, index=False)
    print(f"Results saved to {OUTPUT_CSV}")

if __name__ == '__main__':
    main()